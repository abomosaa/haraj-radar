"use strict";
// Builds the browser-only, installable version into ../web-app/
// (no server, no console window). Run:  node build-web.js
// Upload the web-app folder to any static https host (Cloudflare Pages,
// GitHub Pages, Netlify) — see web-app/README.md.
const fs = require("fs");
const path = require("path");

const SRC = path.join(__dirname, "public");
const OUT = path.resolve(__dirname, "..", "web-app");
fs.mkdirSync(path.join(OUT, "icons"), { recursive: true });

const copy = (from, to) => fs.copyFileSync(from, path.join(OUT, to));
for (const f of ["styles.css", "app.js", "manifest.webmanifest"]) copy(path.join(SRC, f), f);
for (const f of fs.readdirSync(path.join(SRC, "icons"))) copy(path.join(SRC, "icons", f), path.join("icons", f));
copy(path.join(__dirname, "web", "local-api.js"), "local-api.js");
copy(path.join(__dirname, "web", "sw.js"), "sw.js");

// query.js is CommonJS for Node; wrap it so it runs in a page or worker as self.HQ.
const q = fs.readFileSync(path.join(__dirname, "query.js"), "utf8");
fs.writeFileSync(path.join(OUT, "query.js"),
  "// Generated by build-web.js from express-app/query.js — edit that file instead.\n" +
  "(function () {\nvar module = { exports: {} };\nvar process = { env: {} };\n" + q +
  "\nself.HQ = module.exports;\n})();\n");

let html = fs.readFileSync(path.join(SRC, "index.html"), "utf8");
html = html.replace('<script src="./app.js" defer></script>',
  '<script src="./query.js" defer></script>\n  <script src="./local-api.js" defer></script>\n  <script src="./app.js" defer></script>');
fs.writeFileSync(path.join(OUT, "index.html"), html);

// Static hosts: no build step, no Jekyll processing on GitHub Pages.
fs.writeFileSync(path.join(OUT, ".nojekyll"), "");
console.log("web app written to " + OUT);
